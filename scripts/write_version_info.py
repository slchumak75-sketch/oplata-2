"""Generate the Windows VS_VERSION_INFO resource used by PyInstaller.

Usage:
    python scripts/write_version_info.py [output-path]

The default output is ``build/version_info.txt``.  The application version
is read from ``src/oplata/__init__.py`` so there is still a single source of
truth together with ``pyproject.toml`` (which must be kept in sync manually
according to the project release process).
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INIT_FILE = ROOT / "src" / "oplata" / "__init__.py"
DEFAULT_OUTPUT = ROOT / "build" / "version_info.txt"

PRODUCT_NAME = "Оплаты — Строймаркет"
COMPANY_NAME = "Строймаркет"
FILE_DESCRIPTION = "Оплаты — Строймаркет: учёт поставок, долгов и оплат"


def application_version() -> str:
    """Return ``__version__`` from the application package."""

    match = re.search(
        r'^__version__\s*=\s*["\'](?P<version>[^"\']+)["\']',
        INIT_FILE.read_text(encoding="utf-8"),
        flags=re.MULTILINE,
    )
    if match is None:
        raise ValueError(f"__version__ not found in {INIT_FILE}")
    return match.group("version")


def version_tuple(version: str) -> tuple[int, int, int, int]:
    """Convert a 1-to-4-part numeric version to a Windows version tuple."""

    raw_parts = version.strip().split(".")
    if not 1 <= len(raw_parts) <= 4 or any(not part.isdigit() for part in raw_parts):
        raise ValueError(f"Unsupported numeric version: {version!r}")

    values = tuple(int(part) for part in raw_parts)
    if any(value > 65_535 for value in values):
        raise ValueError(f"Windows version components must be <= 65535: {version!r}")
    return values + (0,) * (4 - len(values))


def render_version_info(version: str | None = None) -> str:
    """Render a PyInstaller ``VSVersionInfo`` text file."""

    version = application_version() if version is None else version
    tuple_text = repr(version_tuple(version))

    return f"""# UTF-8
#
# Windows version resource for Oplata.exe.
# Generated by scripts/write_version_info.py; do not edit by hand.
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers={tuple_text},
    prodvers={tuple_text},
    mask=0x3f,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0)
  ),
  kids=[
    StringFileInfo(
      [
        StringTable(
          '041904B0',
          [
            StringStruct('CompanyName', {COMPANY_NAME!r}),
            StringStruct('FileDescription', {FILE_DESCRIPTION!r}),
            StringStruct('FileVersion', {version!r}),
            StringStruct('InternalName', 'Oplata'),
            StringStruct('OriginalFilename', 'Oplata.exe'),
            StringStruct('ProductName', {PRODUCT_NAME!r}),
            StringStruct('ProductVersion', {version!r})
          ]
        )
      ]
    ),
    VarFileInfo([VarStruct('Translation', [1049, 1200])])
  ]
)
"""


def main(argv: list[str] | None = None) -> int:
    args = sys.argv[1:] if argv is None else argv
    if len(args) > 1:
        raise SystemExit("Usage: python scripts/write_version_info.py [output-path]")

    output = Path(args[0]) if args else DEFAULT_OUTPUT
    if not output.is_absolute():
        output = ROOT / output
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(render_version_info(), encoding="utf-8", newline="\n")
    print(output)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
