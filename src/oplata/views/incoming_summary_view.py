"""Сводка поступлений: помесячно, поквартально и за год (v0.32.0).

Запрос пользователя: рядом со «Сводкой оплат» — такая же сводка
поступлений. Считаем входящие деньги активной базы (МИР или КОРЕЛИЧИ —
та, что открыта переключателем в шапке), строки повторяют блок
«Поступление»:

* «Поступление наличными» и «Поступление по картам» — записи кассы;
* «Покупатели» — оплаты, пришедшие от покупателей;
* «Прочие поступления» и каждый добавленный прочий вид;
* строка «Всего» — итог по месяцу, кварталу и году.

Формула — ``calc.incoming_summary``; здесь только показ. Само окно
(таблица, выбор года, ширины колонок) общее со «Сводкой оплат» —
``MonthSummaryDialog``.
"""

from __future__ import annotations

from .. import calc
from .month_summary_view import MonthSummaryDialog


class IncomingSummaryDialog(MonthSummaryDialog):
    """Окно «Сводка поступлений»: виды поступлений × месяцы, кварталы."""

    TITLE = "Сводка поступлений"
    PERIOD_WORD = "Поступления"
    KIND_COLUMN_TITLE = "Вид поступления"

    def summary(self) -> calc.PaymentsSummary:
        return calc.incoming_summary(self.store.data, self.current_year())
