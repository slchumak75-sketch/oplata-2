"""Сводка оплат: помесячно, поквартально и за год (v0.31.0).

Запрос пользователя: в панели «Сводка» — кнопка «Сводка оплат», за
ней — сводная таблица оплат **помесячно и за квартал**.

Считаем исходящие оплаты активной базы (МИР или КОРЕЛИЧИ — та, что
открыта переключателем в шапке):

* строка «Поставщики» — операции вида «Оплата» по поставщикам
  (v0.32.0: оплата покупателя уходит в «Сводку поступлений»);
* по строке на каждый прочий вид оплаты (как в блоке «Оплата»);
* строка «Всего» — итог по месяцу, кварталу и году.

Формула — ``calc.payments_summary``; здесь только показ. Само окно
(таблица, выбор года, ширины колонок) общее со «Сводкой
поступлений» — ``MonthSummaryDialog``.
"""

from __future__ import annotations

from .. import calc
from .month_summary_view import MonthSummaryDialog


class PaymentsSummaryDialog(MonthSummaryDialog):
    """Окно «Сводка оплат»: виды оплат × месяцы, кварталы, год."""

    TITLE = "Сводка оплат"
    PERIOD_WORD = "Оплаты"
    KIND_COLUMN_TITLE = "Вид оплаты"

    def summary(self) -> calc.PaymentsSummary:
        return calc.payments_summary(self.store.data, self.current_year())
